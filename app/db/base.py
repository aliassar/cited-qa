"""
SQLAlchemy declarative base and shared column mixins.

THE NAMING CONVENTION
---------------------
Without it, SQLAlchemy lets the database auto-name indexes and constraints
("documents_org_id_fkey1"). Alembic then cannot reliably generate a DROP for
them, because it does not know the name it must drop. Fixing the convention up
front makes autogenerated migrations deterministic and reversible. This is a
small thing that saves real pain six months in.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime

from sqlalchemy import DateTime, MetaData, String
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)


def utcnow() -> datetime:
    """
    Timezone-AWARE UTC now.

    `datetime.utcnow()` returns a *naive* datetime that merely happens to hold
    UTC. Compare it with an aware datetime and Python raises TypeError; store it
    and you lose the information that it was UTC. Always use aware datetimes.
    """
    return datetime.now(UTC)


def new_uuid() -> str:
    """
    UUID4 as a 32-char hex string.

    Stored as text so the same models run on both SQLite (tests) and Postgres
    (production) without dialect-specific types. In a Postgres-only codebase you
    would use the native UUID column, and probably UUIDv7 - it is time-ordered,
    so it keeps B-tree inserts sequential instead of scattering them across the
    index the way random UUID4s do.
    """
    return uuid.uuid4().hex


class TimestampMixin:
    """created_at / updated_at handled by the ORM, not by the caller."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow, nullable=False, index=True
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=utcnow,
        onupdate=utcnow,  # SQLAlchemy sets this on every UPDATE
        nullable=False,
    )


class UUIDPrimaryKeyMixin:
    id: Mapped[str] = mapped_column(String(32), primary_key=True, default=new_uuid)
